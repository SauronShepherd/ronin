from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path
from types import SimpleNamespace
from typing import Any
from xml.etree import ElementTree

from tools.pytest_timing_report import _skip_reason, _test_summary


def test_skip_reason_keeps_pytest_skip_explanation() -> None:
    report = SimpleNamespace(outcome="skipped", longrepr="integration service unavailable")

    assert _skip_reason(report) == "integration service unavailable"


def test_skip_reason_uses_expected_failure_reason() -> None:
    report = SimpleNamespace(
        outcome="skipped", longrepr="test body", wasxfail="known upstream limitation"
    )

    assert _skip_reason(report) == "known upstream limitation"


def test_skip_reason_reports_missing_reason_explicitly() -> None:
    report = SimpleNamespace(outcome="skipped", longrepr=None)

    assert _skip_reason(report) == "pytest reported a skip without a reason"


def test_test_summary_distinguishes_selected_outcomes_and_unexecuted_items() -> None:
    tests: list[dict[str, Any]] = [
        {"outcome": "passed"},
        {"outcome": "skipped"},
        {"outcome": "failed"},
        {"outcome": "xfailed"},
    ]

    assert _test_summary(tests, selected_count=6, filtered_out_count=20) == {
        "selected": 6,
        "selected_test_items": 6,
        "collection_skipped": 0,
        "filtered_out": 20,
        "executed": 4,
        "not_executed": 2,
        "outcomes": {
            "passed": 1,
            "failed": 1,
            "skipped": 1,
            "xfailed": 1,
            "xpassed": 0,
            "unknown": 0,
        },
    }


def test_pytest_plugin_writes_scope_outcomes_and_skip_reasons(tmp_path: Path) -> None:
    sample = tmp_path / "test_sample.py"
    skipped_module = tmp_path / "test_skipped_module.py"
    config = tmp_path / "pytest.ini"
    config.write_text("[pytest]\n", encoding="utf-8")
    sample.write_text(
        "import pytest\n"
        "def test_passes(): pass\n"
        "def test_skips(): pytest.skip('optional service missing')\n"
        "def test_filtered_out(): pass\n",
        encoding="utf-8",
    )
    skipped_module.write_text(
        "import pytest\n"
        "pytest.skip('optional module dependency missing', allow_module_level=True)\n",
        encoding="utf-8",
    )
    timing_path = tmp_path / "pytest-timings.json"
    junit_path = tmp_path / "pytest-report.xml"
    repository_root = Path(__file__).resolve().parents[1]
    environment = os.environ.copy()
    environment["RONIN_PYTEST_TIMINGS_PATH"] = str(timing_path)

    # Use the fixed Python interpreter and argv list; never invoke a shell.
    result = subprocess.run(  # noqa: S603
        [
            sys.executable,
            "-m",
            "pytest",
            "-q",
            f"--junitxml={junit_path}",
            "-c",
            str(config),
            "-p",
            "tools.pytest_timing_report",
            "-k",
            "passes or skips",
            str(sample),
            str(skipped_module),
        ],
        check=False,
        capture_output=True,
        cwd=repository_root,
        env=environment,
        text=True,
    )

    assert result.returncode == 0, result.stdout + result.stderr
    report = json.loads(timing_path.read_text(encoding="utf-8"))
    assert report["schema"] == "ronin.pytest-timing-evidence/v4"
    assert report["summary"] == {
        "selected": 3,
        "selected_test_items": 2,
        "collection_skipped": 1,
        "filtered_out": 1,
        "executed": 3,
        "not_executed": 0,
        "outcomes": {
            "passed": 1,
            "failed": 0,
            "skipped": 2,
            "xfailed": 0,
            "xpassed": 0,
            "unknown": 0,
        },
    }
    assert len(report["selected_nodeids"]) == 2
    assert len(report["filtered_out_nodeids"]) == 1
    assert report["collection_skips"] == [
        {
            "nodeid": "test_skipped_module.py",
            "outcome": "skipped",
            "skip_reason": "optional module dependency missing",
        }
    ]
    junit = ElementTree.parse(junit_path).getroot()  # noqa: S314 - generated by local pytest
    junit_cases = list(junit.iter("testcase"))
    assert len(junit_cases) == report["summary"]["executed"]
    assert (
        sum(case.find("skipped") is not None for case in junit_cases)
        == report["summary"]["outcomes"]["skipped"]
    )
    skipped = next(test for test in report["tests"] if test["outcome"] == "skipped")
    assert "optional service missing" in skipped["skip_reason"]
